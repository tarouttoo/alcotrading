//! Интенты стратегии: выставить или снять ордер. Интент — запрос, а не
//! приказ: это граница риск-контура (kill-switch, лимит позиции и убытка —
//! в ядре, не в стратегии), который может отклонить запрос до исполнения.
//! Внутри стратегии ни сети, ни async — только эти значения на выходе.

use alko_core::Pair;

/// Сторона ордера: `Buy` — заявка на покупку (bid), `Sell` — на продажу
/// (ask). Не путать со стороной тейкера сделки ([`alko_core::TradeSide`]):
/// сторона ордера — что хочет стратегия, сторона тейкера — что случилось на
/// бирже; отдельный тип не даёт перепутать одно с другим.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Side {
    /// Заявка на покупку (bid).
    Buy,
    /// Заявка на продажу (ask).
    Sell,
}

/// Выставить пассивный лимитный ордер. Модель исполнения фазы 1 — maker:
/// пассивная заявка исполняется только рыночной сделкой по её цене, с
/// учётом очереди (спека #13), рыночных ордеров в интентах нет.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Place {
    /// Пара ордера (`BASEUSDT`, ADR 0004): стратегия может торговать
    /// несколькими парами, интент обязан их различать.
    pub pair: Pair,
    /// Клиентский идентификатор ордера, выбранный самой стратегией;
    /// уникален среди её активных ордеров. Исполнение и риск-контур ссылаются
    /// на ордер по этому идентификатору — обработчики стратегии синхронны,
    /// биржевого идентификатора у них нет.
    pub client_id: u64,
    /// Сторона ордера (bid/ask).
    pub side: Side,
    /// Цена лимитного ордера.
    pub price: f64,
    /// Количество в базовом активе, абсолютное (как у уровней книги).
    pub qty: f64,
}

/// Снять ранее выставленный ордер по его клиентскому идентификатору.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Cancel {
    /// Пара ордера.
    pub pair: Pair,
    /// Клиентский идентификатор из [`Place`].
    pub client_id: u64,
}

/// Интент стратегии: единственное, что стратегия может «сделать» —
/// попросить выставить или снять ордер. Исполнение, риск-контур и учёт
/// позиций — снаружи (спека #13).
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Intent {
    /// Выставить пассивный лимитный ордер.
    Place(Place),
    /// Снять ордер по клиентскому идентификатору.
    Cancel(Cancel),
}
