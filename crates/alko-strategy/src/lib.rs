//! `alko-strategy`: синхронный интерфейс стратегии и граница риск-контура
//! (тикет #17). Стратегия — чистый синхронный обработчик: никакой сети и
//! async, на входе только нормализованные события [`alko_core::Event`]
//! единого формата для всех бирж (без служебных полей — меток
//! последовательностей и поправки часов), на выходе — интенты
//! «выставить/снять ордер». Исполнение, риск-контур (kill-switch, лимит
//! позиции и убытка) и учёт позиций живут снаружи стратегии (спека #13);
//! настоящих стратегий фаза 1 не содержит — только заглушка [`NoOp`].
//!
//! Доставку событий в стратегию ведёт [`feed`] — одна точка маршрутизации
//! для replay и paper, чтобы стратегия видела одинаковую картину в
//! бэктесте и в live.

mod feed;
mod intent;
mod noop;
mod view;

pub use feed::feed;
pub use intent::{Cancel, Intent, Place, Side};
pub use noop::NoOp;
pub use view::{BookView, TradeView};

// Типы alko-core из сигнатур интерфейса — реэкспорт авторам стратегий,
// чтобы интерфейс читался из одного крейта.
pub use alko_core::{Level, Pair, Timestamps, Trade};

/// Синхронный интерфейс стратегии (спека #13): три обработчика, каждый
/// возвращает интенты. Внутри обработчиков нет сети и async — только
/// вычисления над доставленным состоянием; всё, что стратегия хочет
/// «сделать», выражается интентом и проходит через риск-контур снаружи.
///
/// Потребитель (replay, paper) вызывает обработчики по одному событию и
/// передаёт тики таймера сам: [`Strategy`] не знает, откуда пришли события
/// и что значит «сейчас» — в live это локальные часы, в replay время события.
pub trait Strategy {
    /// Обновление книги одной пары. Флаг [`BookView::valid`] обязан
    /// проверяться перед использованием уровней: при `false` содержимое —
    /// последнее валидное, устаревшее (разрыв до следующего снимка).
    fn on_book_update(&mut self, update: &BookView<'_>) -> Vec<Intent>;

    /// Сырая сделка (ADR 0006) одной пары.
    fn on_trade(&mut self, trade: TradeView) -> Vec<Intent>;

    /// Тик таймера от потребителя стратегии: `now_us` — текущее время в
    /// микросекундах UTC (смысл «сейчас» задаёт потребитель: локальные часы
    /// в live, время события в replay).
    fn on_timer(&mut self, now_us: i64) -> Vec<Intent>;
}
