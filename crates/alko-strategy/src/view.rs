//! Что видит стратегия в нормализованном событии: доменные поля без
//! служебных. Метки последовательностей ([`alko_core::BookSeq`]) и поправка
//! часов биржи до стратегии не доходят (тикет #17); флаг валидности книги —
//! часть события, стратегия обязана его проверять перед использованием
//! уровней (глоссарий).

use alko_core::{Level, Pair, Timestamps, Trade};

/// Обновление книги для стратегии: уровни, валидность, пара и метки PERD
/// (ADR 0005). При `valid == false` содержимое — последнее валидное, то есть
/// устаревшее: использовать уровни нельзя до следующего снимка.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BookView<'a> {
    /// Канонический идентификатор пары (`BASEUSDT`, ADR 0004).
    pub pair: Pair,
    /// Метки времени PERD события; `delivered` проставляет потребитель
    /// стратегии на своей копии события до доставки (ADR 0005).
    pub ts: Timestamps,
    /// Заявки (bids), по убыванию цены, топ-20.
    pub bids: &'a [Level],
    /// Запросы (asks), по возрастанию цены, топ-20.
    pub asks: &'a [Level],
    /// Валидность книги: снимок применён и разрыва нет.
    pub valid: bool,
}

/// Сделка для стратегии: сырая сделка (ADR 0006) как часть нормализованного
/// события, с парой и метками PERD.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct TradeView {
    /// Канонический идентификатор пары (`BASEUSDT`, ADR 0004).
    pub pair: Pair,
    /// Метки времени PERD события; `delivered` проставляет потребитель.
    pub ts: Timestamps,
    /// Сырая сделка: цена, количество, сторона тейкера, нативный
    /// идентификатор биржи.
    pub trade: Trade,
}
